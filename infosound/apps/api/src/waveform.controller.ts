import { Controller, Get, Header, NotFoundException, Param } from '@nestjs/common';
import { ApiOkResponse, ApiOperation, ApiTags } from '@nestjs/swagger';
import { db } from '@infosound/database';
import { Current, type Identity, Public } from './security';
import { publicTrackWhere, uuid } from './helpers';

const waveformView = {
  type: 'object' as const,
  required: ['trackId', 'sourceVersion', 'status', 'duration', 'peaks'],
  properties: {
    trackId: { type: 'string' as const, format: 'uuid' },
    sourceVersion: { type: 'integer' as const, minimum: 1 },
    status: { type: 'string' as const, enum: ['READY', 'PENDING', 'UNAVAILABLE'] },
    duration: { type: 'number' as const, nullable: true, minimum: 0, maximum: 900 },
    peaks: {
      type: 'array' as const,
      nullable: true,
      minItems: 512,
      maxItems: 512,
      items: { type: 'number' as const, minimum: 0, maximum: 1 },
    },
  },
};

@ApiTags('InfoSound waveform')
@Controller('api/v1')
export class WaveformController {
  @Public()
  @Get('tracks/:id/waveform')
  @Header('Cache-Control', 'private, no-store')
  @ApiOperation({
    summary:
      'Real source-versioned waveform peaks generated by the sandboxed audio worker; read-only and no placeholder peaks',
  })
  @ApiOkResponse({ schema: waveformView })
  async read(@Param('id') id: string, @Current() identity?: Identity) {
    const track = await db.track.findFirst({
      where: {
        id: uuid(id),
        deletedAt: null,
        OR: [publicTrackWhere, ...(identity ? [{ authorId: identity.id }] : [])],
      },
      select: {
        id: true,
        sourceVersion: true,
        pipelineVersion: true,
        playbackAssetId: true,
        processingState: true,
        waveform: true,
      },
    });
    if (!track)
      throw new NotFoundException({ code: 'TRACK_NOT_FOUND', message: 'Không tìm thấy bài hát.' });
    const stored = track.waveform;
    const matches =
      stored?.sourceVersion === track.sourceVersion &&
      stored?.pipelineVersion === track.pipelineVersion &&
      stored?.playbackAssetId === track.playbackAssetId;
    const ready =
      track.processingState === 'READY' &&
      matches &&
      stored?.status === 'SUCCEEDED' &&
      typeof stored.duration === 'number' &&
      Number.isFinite(stored.duration) &&
      stored.duration > 0 &&
      stored.duration <= 900 &&
      Array.isArray(stored.peaks) &&
      stored.peaks.length === 512 &&
      stored.peaks.every(
        (value) => typeof value === 'number' && Number.isFinite(value) && value >= 0 && value <= 1,
      );
    const status = ready
      ? 'READY'
      : track.processingState !== 'READY' ||
          !track.playbackAssetId ||
          (matches && stored?.status === 'FAILED')
        ? 'UNAVAILABLE'
        : 'PENDING';
    return {
      trackId: track.id,
      sourceVersion: track.sourceVersion,
      status,
      duration: ready ? stored!.duration : null,
      peaks: ready ? stored!.peaks : null,
    };
  }
}
