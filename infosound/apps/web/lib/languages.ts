export type Language = (typeof languages)[number];
export type Locale = Language['code'];
export const localeCookie = 'infosound-locale';

/** Resolve only known codes/tags, preserving vi as the default for bad cookies. */
export function resolveLocale(value: unknown): Locale {
  if (typeof value !== 'string') return 'vi';
  const code = value.trim().toLowerCase();
  const legacy: Readonly<Record<string, Locale>> = {
    zh: 'zh-CN',
    'zh-hans': 'zh-CN',
    'zh-hant': 'zh-TW',
    iw: 'he',
    jw: 'jv',
    fil: 'tl',
    nb: 'no',
  };
  return (
    languages.find(
      (language) => language.code.toLowerCase() === code || language.tag.toLowerCase() === code,
    )?.code ?? (Object.hasOwn(legacy, code) ? legacy[code] : 'vi')
  );
}

export function getLanguage(value: unknown): Language {
  const locale = resolveLocale(value);
  return languages.find((language) => language.code === locale)!;
}
